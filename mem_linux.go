//go:build linux

package main

import (
	"os"
	"strconv"
	"strings"
)

// platformMemAvailable reports the kernel's estimate of memory that can be
// allocated without swapping. It returns 0 when unknown.
func platformMemAvailable() uint64 {
	data, err := os.ReadFile("/proc/meminfo")
	if err != nil {
		return 0
	}
	for _, line := range strings.Split(string(data), "\n") {
		if !strings.HasPrefix(line, "MemAvailable:") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 {
			return 0
		}
		kb, err := strconv.ParseUint(fields[1], 10, 64)
		if err != nil {
			return 0
		}
		return kb * 1024
	}
	return 0
}

